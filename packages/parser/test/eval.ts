/** `pnpm parser:eval`: scores the parser on 3 seasons and writes REPORT.md. */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { evaluate, loadSeason, pct, SEASONS, type EvalResult } from './harness.ts';

const lines: string[] = [];
const all: EvalResult[] = [];
for (const s of SEASONS) {
  const r = evaluate(loadSeason(s), 2000);
  all.push(r);
  lines.push(
    `| ${s} | ${r.plays} | ${pct(r.type)} | ${pct(r.yards)} | ${pct(r.direction)} | ${pct(r.result)} |`,
  );
}
const sum = (k: 'type' | 'yards' | 'direction' | 'result') => ({
  ok: all.reduce((a, r) => a + r[k].ok, 0),
  n: all.reduce((a, r) => a + r[k].n, 0),
});
const total = {
  type: sum('type'),
  yards: sum('yards'),
  direction: sum('direction'),
  result: sum('result'),
};
const plays = all.reduce((a, r) => a + r.plays, 0);
lines.push(
  `| **All** | ${plays} | **${pct(total.type)}** | **${pct(total.yards)}** | **${pct(total.direction)}** | **${pct(total.result)}** |`,
);

const confusion: Record<string, number> = {};
for (const r of all)
  for (const [k, v] of Object.entries(r.confusion)) confusion[k] = (confusion[k] ?? 0) + v;
const topConfusion = Object.entries(confusion)
  .sort((a, b) => b[1] - a[1])
  .slice(0, 12)
  .map(([k, v]) => `| ${k} | ${v} |`);

const byMetric = (m: string) =>
  all
    .flatMap((r) => r.mismatches)
    .filter((x) => x.metric === m)
    .slice(0, 8)
    .map((x) => `- expected \`${x.expected}\`, got \`${x.got}\`: ${x.desc.replace(/\|/g, '/')}`);

const report = `# Parser accuracy report

Generated by \`pnpm parser:eval\` against nflverse labels (\`data/fixtures/nflverse/parser_eval_*.csv.gz\`).
Target: 95%+ on play type, yards and direction (PRD).

| Season | Plays | Play type | Yards | Direction | Pass result |
| --- | --- | --- | --- | --- | --- |
${lines.join('\n')}

- **Play type**: parsed type vs nflverse \`play_type\` (sacks and spikes split out, \`no_play\` = penalty or other).
- **Yards**: parsed yards vs \`yards_gained\` on runs, passes, sacks and kneels (two-point tries excluded).
- **Direction**: parsed direction vs \`pass_location\` / \`run_location\` where labeled.
- **Pass result**: complete / incomplete / interception vs \`complete_pass\` / \`interception\`.

## Most common type confusions (expected -> parsed)

| Confusion | Count |
| --- | --- |
${topConfusion.join('\n')}

## Sample mismatches

### Type
${byMetric('type').join('\n')}

### Yards
${byMetric('yards').join('\n')}

### Direction
${byMetric('direction').join('\n')}
`;
writeFileSync(join(import.meta.dirname, '../REPORT.md'), report);
